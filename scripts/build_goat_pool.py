"""Regenerate api/_goat_cards.py, the GOAT format card pool used by the deckbuilder.

Source of truth is Format Library's GOAT format: every TCG card released on or
before 2005-08-20 (SJC Indianapolis) with the April 2005 banlist. YGOPRODeck
supplies the type/race/archetype fields the search filters use and the
alternate-artwork ids. GOAT is a frozen format, so this only needs re-running if
Format Library corrects its data.

Usage: python scripts/build_goat_pool.py
"""
import json
import os
import time
import urllib.parse
import urllib.request

FL = "https://formatlibrary.com/api"
YPD = "https://db.ygoprodeck.com/api/v7/cardinfo.php"
CUTOFF = "2005-08-20"
BANLIST = "April 2005"
OUT = os.path.join(os.path.dirname(__file__), "..", "api", "_goat_cards.py")
EXTRA_TYPES = ("Fusion", "Synchro", "XYZ", "Link")
BAN_NAMES = {"forbidden": "Forbidden", "limited": "Limited", "semi-limited": "Semi-Limited"}


def get_json(url):
    req = urllib.request.Request(url, headers={"User-Agent": "ygo-tcg-ph-swiss-maker"})
    return json.load(urllib.request.urlopen(req, timeout=60))


def format_library_cards():
    rows, page = [], 1
    while True:
        batch = get_json(f"{FL}/cards?limit=100&page={page}&sort=name:asc&filter=tcgDate:lte:{CUTOFF}")
        if not batch:
            return rows
        rows += batch
        page += 1
        time.sleep(0.3)


def ygoprodeck_cards():
    # The full database in one request: lookups by id only return that id's artwork,
    # but we need every alternate-artwork id to recognise older saved decklists.
    return {str(c["id"]): c for c in get_json(YPD).get("data", [])}


def monster_type(r):
    if r["isFusion"]:
        return "Fusion Monster"
    if r["isRitual"]:
        return "Ritual Effect Monster" if r["isEffect"] else "Ritual Monster"
    for flag, name in (("isFlip", "Flip Effect Monster"), ("isUnion", "Union Effect Monster"), ("isSpirit", "Spirit Monster"),
                       ("isToon", "Toon Monster"), ("isGemini", "Gemini Monster")):
        if r[flag]:
            return name
    return "Effect Monster" if r["isEffect"] else "Normal Monster"


def main():
    fl = format_library_cards()
    ban_raw = get_json(f"{FL}/banlists/cards/{urllib.parse.quote(BANLIST)}?category=TCG")
    bans = {int(k): BAN_NAMES.get(v) for k, v in ban_raw.items()}
    ypd = ygoprodeck_cards()
    # Format Library sometimes uses an alternate-artwork id; resolve via any artwork id.
    by_artwork = {str(img["id"]): c for c in ypd.values() for img in (c.get("card_images") or [])}

    cards, aliases = [], {}
    for r in fl:
        y = ypd.get(r["ypdId"]) or by_artwork.get(r["ypdId"])
        cid = y["id"] if y else int(r["ypdId"])
        if y:
            if int(r["ypdId"]) != cid:
                aliases[int(r["ypdId"])] = cid
            card = {
                "id": cid, "name": y["name"], "type": y["type"], "race": y.get("race"),
                "attribute": y.get("attribute"), "level": y.get("level"), "atk": y.get("atk"), "def": y.get("def"),
                "desc": y.get("desc"), "archetype": y.get("archetype"),
                "extra": any(t in y["type"] for t in EXTRA_TYPES),
            }
            for img in y.get("card_images") or []:
                if img["id"] != cid:
                    aliases[img["id"]] = cid
        else:  # Not on YGOPRODeck (e.g. Ulevo, Meteo the Matchless): build from Format Library.
            is_monster = r["category"] == "Monster"
            card = {
                "id": cid, "name": r["name"],
                "type": monster_type(r) if is_monster else f"{r['category']} Card",
                "race": r["type"] if is_monster else r["icon"],
                "attribute": r["attribute"], "level": r["level"], "atk": r["atk"], "def": r["def"],
                "desc": r["description"], "archetype": None, "extra": bool(r["isExtraDeck"]),
            }
        card["ban"] = bans.get(r["id"])
        card["img"] = cid
        cards.append(card)

    cards.sort(key=lambda c: c["name"].lower())
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("# Generated by scripts/build_goat_pool.py. Do not edit by hand.\n")
        f.write(f"# GOAT format per Format Library: TCG cards released by {CUTOFF}, {BANLIST} banlist.\n")
        f.write(f"CARDS = {cards!r}\n")
        f.write(f"ALIASES = {aliases!r}\n")
    missing = [c["name"] for c in cards if not ypd.get(str(c["id"]))]
    print(f"Wrote {len(cards)} cards ({sum(1 for c in cards if c['ban'])} on the banlist, "
          f"{len(aliases)} alternate artworks) to {os.path.normpath(OUT)}")
    print("Built from Format Library data (not on YGOPRODeck):", missing)


if __name__ == "__main__":
    main()
